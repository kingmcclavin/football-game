#!/usr/bin/env python3
"""Cut player animation frames out of the JordanTRS football sprite sheet
(assets/players_jordantrs.png) and write them as 32x32 ASCII sprites to
assets/players.txt, using the 'team' palette legend of gen_assets.py.

The sheet draws players in key colours on black; each key colour becomes a
palette index that the game recolours per team at runtime.
Credit: player sprites by JordanTRS.
"""
import os
import sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "assets", "players_jordantrs.png")
OUT = os.path.join(ROOT, "assets", "players.txt")

# key colour -> legend letter (see TEAM_LEGEND in gen_assets.py)
KEYS = {
    (0, 0, 0): ".",
    (255, 0, 0): "H", (128, 0, 0): "h",           # helmet, helmet stripe
    (158, 158, 158): "M", (128, 128, 128): "m",   # facemask
    (0, 0, 255): "S", (0, 0, 128): "s",           # skin, skin shade
    (128, 128, 255): "J",                         # jersey
    (255, 0, 255): "P", (128, 0, 128): "p",       # pants
    (0, 255, 0): "O", (0, 128, 0): "o", (0, 127, 0): "o",  # socks
    (255, 255, 0): "B",                           # cleats
    (76, 31, 17): "F", (122, 25, 16): "F", (118, 32, 24): "F", (174, 0, 0): "F",
    (40, 5, 20): "F", (185, 137, 91): "F",        # football
    (236, 236, 236): "W", (255, 255, 255): "W",
    (87, 0, 174): "s",
}
BG = {(44, 104, 255), (31, 73, 178)}

# (name, top-left x, top-left y) of each frame's black box on the sheet.
# The order defines the FR_* enum in play.h.
FRAMES = [
    ("stand", 28, 599), ("stand_ball", 28, 652),
    ("run1", 339, 37), ("run2", 379, 36), ("run3", 421, 36), ("run4", 465, 37), ("run5", 505, 36), ("run6", 547, 36),
    ("runb1", 339, 92), ("runb2", 378, 91), ("runb3", 420, 91), ("runb4", 464, 92), ("runb5", 504, 91), ("runb6", 546, 91),
    ("aim", 26, 89), ("throw", 27, 195),
    ("catch1", 382, 295), ("catch2", 424, 292), ("catch3", 466, 295),
    ("fall", 172, 651), ("down", 210, 662),
    ("block1", 167, 599), ("block2", 211, 599),
    ("dive1", 334, 517), ("dive2", 375, 519), ("dive3", 417, 522),
    ("celeb1", 29, 474), ("celeb2", 70, 477),
    ("stiff", 421, 143), ("kneel", 340, 676),
    ("down_ball", 211, 713), ("fall_ball", 172, 704),
]


def grab(im, x, y):
    """Flood-fill the sprite box starting at (x, y); return its pixels."""
    W, H = im.size
    px = im.load()
    seen = {(x, y)}
    stack = [(x, y)]
    while stack:
        a, b = stack.pop()
        for c, d in ((a + 1, b), (a - 1, b), (a, b + 1), (a, b - 1)):
            if 0 <= c < W and 0 <= d < H and (c, d) not in seen and px[c, d] not in BG:
                seen.add((c, d))
                stack.append((c, d))
    xs = [p[0] for p in seen]
    ys = [p[1] for p in seen]
    x0, y0 = min(xs), min(ys)
    w, h = max(xs) - x0 + 1, max(ys) - y0 + 1
    rows = []
    for j in range(h):
        row = ""
        for i in range(w):
            p = (x0 + i, y0 + j)
            c = px[p] if p in seen else (0, 0, 0)
            if c in KEYS:
                row += KEYS[c]
            elif c[0] == c[1] == c[2]:
                row += "W" if c[0] > 200 else "M" if c[0] > 140 else "m" if c[0] > 60 else "K"
            elif c[0] > c[1] and c[0] > c[2] and c[0] < 200:
                row += "F"  # other shades of the leather ball
            else:
                sys.exit("unknown colour %r at %r" % (c, p))
        rows.append(row)
    # trim empty borders
    while rows and set(rows[0]) == {"."}:
        rows.pop(0)
    while rows and set(rows[-1]) == {"."}:
        rows.pop()
    left = min(len(r) - len(r.lstrip(".")) for r in rows)
    right = max(len(r.rstrip(".")) for r in rows)
    return [r[left:right] for r in rows]


def main():
    im = Image.open(SRC).convert("RGB")
    out = ["# Generated by tools/import_sheet.py from assets/players_jordantrs.png.",
           "# Player sprites by JordanTRS (credit required). 32x32, feet on row 30.", ""]
    for name, x, y in FRAMES:
        rows = grab(im, x, y)
        h, w = len(rows), max(len(r) for r in rows)
        if h > 31 or w > 32:
            sys.exit("frame %s too big (%dx%d)" % (name, w, h))
        canvas = [["."] * 32 for _ in range(32)]
        ox = 16 - (w + 1) // 2
        oy = 31 - h
        for j, r in enumerate(rows):
            for i, ch in enumerate(r):
                canvas[oy + j][ox + i] = ch
        out.append("=pf_%s 32x32 team" % name)
        out.extend("".join(r) for r in canvas)
        out.append("")
        print("%-10s %2dx%2d" % (name, w, h))
    open(OUT, "w").write("\n".join(out))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
