#!/usr/bin/env python3
"""Fix up a GBA ROM header: Nintendo logo, title, game code and checksum.

Usage: gbafix.py ROM.gba [--title TITLE] [--code CODE] [--maker MK]

The logo bytes are required by the GBA BIOS boot check on real hardware
(and on emulators configured to use a real BIOS). They are the standard
values used by every homebrew header fixer (devkitPro gbafix, the Rust
gbafix crate, etc.).
"""
import sys

LOGO = bytes([
    0x24, 0xFF, 0xAE, 0x51, 0x69, 0x9A, 0xA2, 0x21, 0x3D, 0x84, 0x82, 0x0A, 0x84,
    0xE4, 0x09, 0xAD, 0x11, 0x24, 0x8B, 0x98, 0xC0, 0x81, 0x7F, 0x21, 0xA3, 0x52,
    0xBE, 0x19, 0x93, 0x09, 0xCE, 0x20, 0x10, 0x46, 0x4A, 0x4A, 0xF8, 0x27, 0x31,
    0xEC, 0x58, 0xC7, 0xE8, 0x33, 0x82, 0xE3, 0xCE, 0xBF, 0x85, 0xF4, 0xDF, 0x94,
    0xCE, 0x4B, 0x09, 0xC1, 0x94, 0x56, 0x8A, 0xC0, 0x13, 0x72, 0xA7, 0xFC, 0x9F,
    0x84, 0x4D, 0x73, 0xA3, 0xCA, 0x9A, 0x61, 0x58, 0x97, 0xA3, 0x27, 0xFC, 0x03,
    0x98, 0x76, 0x23, 0x1D, 0xC7, 0x61, 0x03, 0x04, 0xAE, 0x56, 0xBF, 0x38, 0x84,
    0x00, 0x40, 0xA7, 0x0E, 0xFD, 0xFF, 0x52, 0xFE, 0x03, 0x6F, 0x95, 0x30, 0xF1,
    0x97, 0xFB, 0xC0, 0x85, 0x60, 0xD6, 0x80, 0x25, 0xA9, 0x63, 0xBE, 0x03, 0x01,
    0x4E, 0x38, 0xE2, 0xF9, 0xA2, 0x34, 0xFF, 0xBB, 0x3E, 0x03, 0x44, 0x78, 0x00,
    0x90, 0xCB, 0x88, 0x11, 0x3A, 0x94, 0x65, 0xC0, 0x7C, 0x63, 0x87, 0xF0, 0x3C,
    0xAF, 0xD6, 0x25, 0xE4, 0x8B, 0x38, 0x0A, 0xAC, 0x72, 0x21, 0xD4, 0xF8, 0x07,
])
assert len(LOGO) == 156


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 1
    path = args[0]
    opts = {"--title": None, "--code": None, "--maker": None}
    i = 1
    while i < len(args):
        if args[i] in opts and i + 1 < len(args):
            opts[args[i]] = args[i + 1]
            i += 2
        else:
            print("unknown argument", args[i])
            return 1
    rom = bytearray(open(path, "rb").read())
    if len(rom) < 0xC0:
        print("ROM too small")
        return 1
    rom[0x04:0xA0] = LOGO
    if opts["--title"]:
        rom[0xA0:0xAC] = opts["--title"].upper().encode("ascii")[:12].ljust(12, b"\0")
    if opts["--code"]:
        rom[0xAC:0xB0] = opts["--code"].upper().encode("ascii")[:4].ljust(4, b"\0")
    if opts["--maker"]:
        rom[0xB0:0xB2] = opts["--maker"].upper().encode("ascii")[:2].ljust(2, b"\0")
    rom[0xB2] = 0x96
    chk = 0
    for b in rom[0xA0:0xBD]:
        chk = (chk - b) & 0xFF
    rom[0xBD] = (chk - 0x19) & 0xFF
    # Pad to a multiple of 256 bytes (some flashcarts/emulators prefer it).
    while len(rom) % 256:
        rom.append(0xFF)
    open(path, "wb").write(rom)
    print("gbafix: %s  size=%d  checksum=0x%02X" % (path, len(rom), rom[0xBD]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
